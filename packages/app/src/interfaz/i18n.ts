const DICCIONARIOS: Record<Idioma, Record<Clave, Texto>> = { es, en };
const LOCALES: Record<Idioma, string> = { es: 'es-MX', en: 'en-US' };

function inicial(): Idioma {
  try {
    const g = localStorage.getItem('motionai.idioma');
    if (g === 'es' || g === 'en') return g;
  } catch { /* sin almacenamiento */ }
  return navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export const idioma = ref<Idioma>(inicial());

watchEffect(() => {
  document.documentElement.lang = idioma.value;
  try { localStorage.setItem('motionai.idioma', idioma.value); } catch { /* sin almacenamiento */ }
  window.motionai?.idioma?.(idioma.value);
});

const plurales = new Map<Idioma, Intl.PluralRules>();

/** Traduce una clave. Con {n} elige la forma en plural correcta. */
export function t(clave: Clave, p: Record<string, string | number> = {}): string {
  const d = DICCIONARIOS[idioma.value];
  let texto = d[clave] ?? es[clave] ?? clave;
  if (typeof texto !== 'string') {
    const n = Number(p.n ?? 0);
    if (n === 0 && texto.zero) texto = texto.zero;
    else {
      let reglas = plurales.get(idioma.value);
      if (!reglas) plurales.set(idioma.value, (reglas = new Intl.PluralRules(LOCALES[idioma.value])));
      texto = reglas.select(n) === 'one' ? texto.one : texto.other;
    }
  }
  return texto.replace(/\{(\w+)\}/g, (_, k) => (p[k] !== undefined ? String(p[k]) : `{${k}}`));
}

/** ¿Existe la clave? Para textos armados (herramientas, movimientos). */
export const hay = (clave: string): clave is Clave => clave in es;

export const numero = (n: number, decimales = 0) =>
  new Intl.NumberFormat(LOCALES[idioma.value], { minimumFractionDigits: decimales, maximumFractionDigits: decimales }).format(n);

export const fecha = (iso: string, estilo: 'larga' | 'hora' = 'larga') =>
  new Date(iso).toLocaleString(LOCALES[idioma.value], estilo === 'hora'
    ? { hour: '2-digit', minute: '2-digit', second: '2-digit' }
    : { dateStyle: 'medium', timeStyle: 'short' });

/** Une una lista: «a, b y c» / «a, b and c». */
export function lista(items: string[]): string {
  if (items.length <= 1) return items[0] ?? '';
  return t('hist.y', { lista: items.slice(0, -1).join(', '), ultimo: items[items.length - 1]! });
}
